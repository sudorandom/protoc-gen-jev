// GeneratePython writes Python client classes into <file>_jev.py.
func GeneratePython(gen *protogen.Plugin, file *protogen.File, specs []model.MessageSpec, serviceSpecs []model.ServiceSpec) {
	filename := fmt.Sprintf("%s_jev.py", file.GeneratedFilenamePrefix)
	g := gen.NewGeneratedFile(filename, "")

	g.P(`"""Generated by protoc-gen-jev. DO NOT EDIT."""`)
	if len(serviceSpecs) > 0 {
		g.P(`from dataclasses import dataclass, asdict`)
	}
	g.P(`from typing import Any, Dict, List, Optional`)
	g.P(`from typesafe_sdk import TypeSafeClient, Choice, Noul, Score`)
	g.P()

	generatedClasses := make(map[string]bool)

	for _, spec := range specs {
		clientName := fmt.Sprintf("%sJevClient", spec.MessageName)

		g.P(fmt.Sprintf(`class %s:`, clientName))
		g.P(fmt.Sprintf(`    """Typed Jev client for evaluating %s."""`, spec.MessageName))
		g.P()
		g.P(`    def __init__(self, client: Optional[TypeSafeClient] = None, api_key: Optional[str] = None):`)
		g.P(`        if client is not None:`)
		g.P(`            self._client = client`)
		g.P(`        elif api_key is not None:`)
		g.P(`            self._client = TypeSafeClient(api_key=api_key)`)
		g.P(`        else:`)
		g.P(`            self._client = None  # Will lazy-init on evaluate() from env`)
		g.P()
		g.P(`    @property`)
		g.P(`    def client(self) -> TypeSafeClient:`)
		g.P(`        if self._client is None:`)
		g.P(`            self._client = TypeSafeClient()`)
		g.P(`        return self._client`)
		g.P()
		g.P(`    def build_questions(self) -> Dict[str, Any]:`)
		g.P(`        """Constructs the native Jev question primitives from the Protobuf schema."""`)
		g.P(`        return {`)

		for _, jsonName := range spec.Order {
			q := spec.Questions[jsonName]
			switch q.Type {
			case model.TypeChoice:
				g.P(fmt.Sprintf(`            %q: Choice(`, jsonName))
				g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
				var critKeys []string
				if m, ok := q.Criteria.(map[string]any); ok {
					var keys []string
					for k := range m {
						keys = append(keys, k)
					}
					sort.Strings(keys)
					for _, k := range keys {
						critKeys = append(critKeys, fmt.Sprintf("%q: None", k))
					}
				}
				g.P(fmt.Sprintf(`                criteria={%s},`, strings.Join(critKeys, ", ")))
				g.P(`            ),`)
			case model.TypeNoul:
				g.P(fmt.Sprintf(`            %q: Noul(`, jsonName))
				g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
				g.P(`            ),`)
			case model.TypeScore:
				g.P(fmt.Sprintf(`            %q: Score(`, jsonName))
				g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
				var critItems []string
				if arr, ok := q.Criteria.([]string); ok {
					for _, item := range arr {
						critItems = append(critItems, fmt.Sprintf("%q", item))
					}
				}
				g.P(fmt.Sprintf(`                criteria=[%s],`, strings.Join(critItems, ", ")))
				g.P(`            ),`)
			}
		}

		g.P(`        }`)
		g.P()
		g.P(`    def evaluate(self, state: Dict[str, Any] | str) -> Dict[str, Any]:`)
		g.P(`        """Evaluates state against Jev System One questions and returns typed decisions."""`)
		g.P(`        payload_state = {"text": state} if isinstance(state, str) else state`)
		g.P(`        questions = self.build_questions()`)
		g.P(`        resp = self.client.system_one(state=payload_state, questions=questions)`)
		g.P(`        out = {}`)

		for _, jsonName := range spec.Order {
			q := spec.Questions[jsonName]
			switch q.Type {
			case model.TypeChoice:
				g.P(fmt.Sprintf(`        if %q in resp.choices:`, jsonName))
				g.P(fmt.Sprintf(`            out[%q] = resp.choices[%q].choice`, q.ProtoField, jsonName))
			case model.TypeNoul:
				g.P(fmt.Sprintf(`        if %q in resp.nouls:`, jsonName))
				g.P(fmt.Sprintf(`            _item = resp.nouls[%q]`, jsonName))
				g.P(fmt.Sprintf(`            out[%q] = getattr(_item, "result", getattr(_item, "noul", False))`, q.ProtoField))
			case model.TypeScore:
				g.P(fmt.Sprintf(`        if %q in resp.scores:`, jsonName))
				g.P(fmt.Sprintf(`            out[%q] = resp.scores[%q].score`, q.ProtoField, jsonName))
			}
		}

		g.P(`        return out`)
		g.P()
		g.P(`    def batch_evaluate(self, states: List[Dict[str, Any] | str]) -> List[Dict[str, Any]]:`)
		g.P(`        """Evaluates a batch of states against Jev."""`)
		g.P(`        return [self.evaluate(s) for s in states]`)
		g.P()
	}

	for _, svc := range serviceSpecs {
		// 1. Generate dataclasses for input and output messages
		for _, m := range svc.Methods {
			if !generatedClasses[m.InputType] {
				generatedClasses[m.InputType] = true
				g.P(`@dataclass`)
				g.P(fmt.Sprintf(`class %s:`, m.InputType))
				g.P(fmt.Sprintf(`    """Input request message for %s."""`, m.Name))
				if len(m.InputFields) == 0 {
					g.P(`    pass`)
				} else {
					for _, f := range m.InputFields {
						pyType := "str"
						pyDefault := `""`
						switch f.Type {
						case "bool":
							pyType = "bool"
							pyDefault = "False"
						case "int32", "int64":
							pyType = "int"
							pyDefault = "0"
						case "float32", "float64":
							pyType = "float"
							pyDefault = "0.0"
						}
						g.P(fmt.Sprintf(`    %s: %s = %s`, f.Name, pyType, pyDefault))
					}
				}
				g.P()
			}

			if !generatedClasses[m.OutputType] {
				generatedClasses[m.OutputType] = true
				g.P(`@dataclass`)
				g.P(fmt.Sprintf(`class %s:`, m.OutputType))
				g.P(fmt.Sprintf(`    """Output decisions message for %s."""`, m.Name))
				for _, name := range m.QuestionSpec.Order {
					q := m.QuestionSpec.Questions[name]
					pyType := "Optional[str]"
					switch q.Type {
					case model.TypeNoul:
						pyType = "Optional[bool]"
					case model.TypeScore:
						pyType = "Optional[float]"
					}
					g.P(fmt.Sprintf(`    %s: %s = None`, q.ProtoField, pyType))
				}
				g.P()
			}
		}

		clientName := fmt.Sprintf("%sClient", svc.ServiceName)
		g.P(fmt.Sprintf(`class %s:`, clientName))
		g.P(fmt.Sprintf(`    """Typed Jev client for %s."""`, svc.ServiceName))
		g.P()
		g.P(`    def __init__(self, client: Optional[TypeSafeClient] = None, api_key: Optional[str] = None):`)
		g.P(`        if client is not None:`)
		g.P(`            self._client = client`)
		g.P(`        elif api_key is not None:`)
		g.P(`            self._client = TypeSafeClient(api_key=api_key)`)
		g.P(`        else:`)
		g.P(`            self._client = None`)
		g.P()
		g.P(`    @property`)
		g.P(`    def client(self) -> TypeSafeClient:`)
		g.P(`        if self._client is None:`)
		g.P(`            self._client = TypeSafeClient()`)
		g.P(`        return self._client`)
		g.P()

		for _, m := range svc.Methods {
			pyMethodName := ToSnakeCase(m.Name)
			buildMethodName := fmt.Sprintf("build_%s_questions", pyMethodName)

			g.P(fmt.Sprintf(`    def %s(self) -> Dict[str, Any]:`, buildMethodName))
			g.P(`        """Constructs the native Jev question primitives from the Protobuf schema."""`)
			g.P(`        return {`)
			for _, jsonName := range m.QuestionSpec.Order {
				q := m.QuestionSpec.Questions[jsonName]
				switch q.Type {
				case model.TypeChoice:
					g.P(fmt.Sprintf(`            %q: Choice(`, jsonName))
					g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
					var critKeys []string
					if mp, ok := q.Criteria.(map[string]any); ok {
						var keys []string
						for k := range mp {
							keys = append(keys, k)
						}
						sort.Strings(keys)
						for _, k := range keys {
							critKeys = append(critKeys, fmt.Sprintf("%q: None", k))
						}
					}
					g.P(fmt.Sprintf(`                criteria={%s},`, strings.Join(critKeys, ", ")))
					g.P(`            ),`)
				case model.TypeNoul:
					g.P(fmt.Sprintf(`            %q: Noul(`, jsonName))
					g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
					g.P(`            ),`)
				case model.TypeScore:
					g.P(fmt.Sprintf(`            %q: Score(`, jsonName))
					g.P(fmt.Sprintf(`                instructions=%q,`, q.Instructions))
					var critItems []string
					if arr, ok := q.Criteria.([]string); ok {
						for _, item := range arr {
							critItems = append(critItems, fmt.Sprintf("%q", item))
						}
					}
					g.P(fmt.Sprintf(`                criteria=[%s],`, strings.Join(critItems, ", ")))
					g.P(`            ),`)
				}
			}
			g.P(`        }`)
			g.P()

			g.P(fmt.Sprintf(`    def %s(self, req: %s | Dict[str, Any]) -> %s:`, pyMethodName, m.InputType, m.OutputType))
			g.P(fmt.Sprintf(`        """Evaluates %s against Jev and returns a typed %s."""`, m.InputType, m.OutputType))
			g.P(fmt.Sprintf(`        payload_state = asdict(req) if isinstance(req, %s) else req`, m.InputType))
			g.P(fmt.Sprintf(`        questions = self.%s()`, buildMethodName))
			g.P(`        resp = self.client.system_one(state=payload_state, questions=questions)`)
			g.P(fmt.Sprintf(`        out = %s()`, m.OutputType))
			for _, jsonName := range m.QuestionSpec.Order {
				q := m.QuestionSpec.Questions[jsonName]
				switch q.Type {
				case model.TypeChoice:
					g.P(fmt.Sprintf(`        if hasattr(resp, "answers") and %q in resp.answers:`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = getattr(resp.answers[%q], "choice", None)`, q.ProtoField, jsonName))
					g.P(fmt.Sprintf(`        elif %q in resp.choices:`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = resp.choices[%q].choice`, q.ProtoField, jsonName))
				case model.TypeNoul:
					g.P(fmt.Sprintf(`        if hasattr(resp, "answers") and %q in resp.answers:`, jsonName))
					g.P(fmt.Sprintf(`            _item = getattr(resp.answers[%q], "noul", None)`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = _item if isinstance(_item, bool) else (_item >= 0.5 if isinstance(_item, (int, float)) else False)`, q.ProtoField))
					g.P(fmt.Sprintf(`        elif %q in resp.nouls:`, jsonName))
					g.P(fmt.Sprintf(`            _item = resp.nouls[%q]`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = getattr(_item, "result", getattr(_item, "noul", False))`, q.ProtoField))
				case model.TypeScore:
					g.P(fmt.Sprintf(`        if hasattr(resp, "answers") and %q in resp.answers:`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = getattr(resp.answers[%q], "score", None)`, q.ProtoField, jsonName))
					g.P(fmt.Sprintf(`        elif %q in resp.scores:`, jsonName))
					g.P(fmt.Sprintf(`            out.%s = resp.scores[%q].score`, q.ProtoField, jsonName))
				}
			}
			g.P(`        return out`)
			g.P()

			batchMethodName := fmt.Sprintf("batch_%s", pyMethodName)
			g.P(fmt.Sprintf(`    def %s(self, reqs: List[%s | Dict[str, Any]]) -> List[%s]:`, batchMethodName, m.InputType, m.OutputType))
			g.P(fmt.Sprintf(`        """Evaluates a batch of %s items against Jev."""`, m.InputType))
			g.P(fmt.Sprintf(`        return [self.%s(r) for r in reqs]`, pyMethodName))
			g.P()
		}
	}
}

// ToSnakeCase converts camelCase or PascalCase to snake_case.
func ToSnakeCase(s string) string {
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}
		result.WriteRune(r)
	}
	return strings.ToLower(result.String())
}
